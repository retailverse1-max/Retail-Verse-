  // ============================================================================
  // AUTOMATIC SKU GENERATION (e.g. "Chips" -> "chips-237")
  // ============================================================================
  void _onProductNameChanged() {
    final name = _nameController.text.trim();
    if (name.isEmpty) {
      if (!_isSkuManuallyEdited) {
        _skuController.text = '';
        _lastAutoGeneratedSku = '';
      }
      return;
    }

    // Auto-generate if user hasn't typed custom SKU or it matches previous auto-SKU
    if (!_isSkuManuallyEdited || _skuController.text == _lastAutoGeneratedSku) {
      final cleanWord = _extractCleanSkuPrefix(name);
      if (cleanWord.isNotEmpty) {
        if (_skuRandomSuffix < 100 || _skuRandomSuffix > 999) {
          _skuRandomSuffix = 100 + (DateTime.now().millisecondsSinceEpoch % 900);
        }
        final newSku = '$cleanWord-$_skuRandomSuffix';
        _lastAutoGeneratedSku = newSku;
        _skuController.text = newSku;
      }
    }
  }

  void _onSkuChanged() {
    if (_skuController.text != _lastAutoGeneratedSku) {
      _isSkuManuallyEdited = _skuController.text.trim().isNotEmpty;
    }
  }

  String _extractCleanSkuPrefix(String name) {
    final words = name.trim().split(RegExp(r'\s+'));
    if (words.isEmpty) return '';
    final first = words.first.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '').toLowerCase();
    return first.isNotEmpty ? first : 'prod';
  }

  void _regenerateSkuSuffix() {
    _skuRandomSuffix = 100 + (DateTime.now().microsecondsSinceEpoch % 900);
    final name = _nameController.text.trim();
    final cleanWord = name.isNotEmpty ? _extractCleanSkuPrefix(name) : 'prod';
    final newSku = '$cleanWord-$_skuRandomSuffix';
    _isSkuManuallyEdited = false;
    _lastAutoGeneratedSku = newSku;
    setState(() {
      _skuController.text = newSku;
    });
    SystemSound.play(SystemSoundType.click);
    HapticFeedback.lightImpact();
  }

  String _getStoreName() {
    try {
      final posSettings = ref.read(posSettingsProvider);
      if (posSettings.storeName.trim().isNotEmpty) {
        return posSettings.storeName.trim();
      }
      final authUser = ref.read(authProvider).user;
      final busName = authUser?['businessName']?.toString() ??
          authUser?['storeName']?.toString() ??
          authUser?['name']?.toString();
      if (busName != null && busName.trim().isNotEmpty) {
        return busName.trim();
      }
    } catch (_) {}
    return 'My Store';
  }

  Future<void> _loadCategories() async {
    setState(() => _isLoadingCategories = true);

    try {
      List<CategoryEntity> categories;
      try {
        categories = await ref.read(categoriesProvider.future);
      } catch (_) {
        categories = await ref.read(categoryRepositoryProvider).getAllCategories();
      }

      if (!mounted) return;
      setState(() {
        _categories = List<CategoryEntity>.from(categories);
        _isLoadingCategories = false;

        if (widget.category != null) {
          final targetId = widget.category!.id;
          final targetName = widget.category!.name.trim().toLowerCase();
          final matchIdx = _categories.indexWhere(
            (c) => c.id == targetId || c.name.trim().toLowerCase() == targetName,
          );
          if (matchIdx != -1) {
            _selectedCategoryId = _categories[matchIdx].id;
          } else {
            final navCategoryEntity = CategoryEntity(
              id: widget.category!.id,
              name: widget.category!.name.trim(),
              subtitle: widget.category!.subtitle,
              imagePath: widget.category!.imagePath,
              productCount: widget.category!.productCount,
              createdAt: DateTime.now(),
              updatedAt: DateTime.now(),
            );
            _categories.insert(0, navCategoryEntity);
            _selectedCategoryId = navCategoryEntity.id;
          }
        } else if (widget.editProduct != null && widget.editProduct!.category.isNotEmpty) {
          final editCat = widget.editProduct!.category.trim().toLowerCase();
          final matchIdx = _categories.indexWhere(
            (c) => c.name.trim().toLowerCase() == editCat || c.id == widget.editProduct!.category,
          );
          if (matchIdx != -1) {
            _selectedCategoryId = _categories[matchIdx].id;
          } else {
            final fallbackEntity = CategoryEntity(
              id: 'cat_${widget.editProduct!.category.toLowerCase().replaceAll(RegExp(r'\s+'), '_')}',
              name: widget.editProduct!.category.trim(),
              subtitle: '',
              imagePath: '',
              productCount: 0,
              createdAt: DateTime.now(),
              updatedAt: DateTime.now(),
            );
            _categories.insert(0, fallbackEntity);
            _selectedCategoryId = fallbackEntity.id;
          }
        } else if (_selectedCategoryId == null && _categories.isNotEmpty) {
          _selectedCategoryId = _categories.first.id;
        }
      });
    } catch (e) {
      if (!mounted) return;
      setState(() {
        _isLoadingCategories = false;
        if (widget.category != null) {
          final navCategoryEntity = CategoryEntity(
            id: widget.category!.id,
            name: widget.category!.name.trim(),
            subtitle: widget.category!.subtitle,
            imagePath: widget.category!.imagePath,
            productCount: widget.category!.productCount,
            createdAt: DateTime.now(),
            updatedAt: DateTime.now(),
          );
          _categories = [navCategoryEntity];
          _selectedCategoryId = navCategoryEntity.id;
        }
      });
      _showSnack('Failed to load categories: ${e.toString()}', isError: true);
    }
  }

