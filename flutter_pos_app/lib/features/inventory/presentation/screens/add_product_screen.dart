  /// Generates real PDF and sends directly to thermal label or laser printer
  /// Optimized for 58mm Billplus thermal printers with 2x1 inch sticker rolls
  Future<void> _printBarcodePdf({
    required String storeName,
    required String productName,
    required String barcode,
    required String size,
    required int copies,
    double? customWidthMm,
    double? customHeightMm,
  }) async {
    try {
      final doc = pw.Document();

      // Determine sticker label dimensions in mm
      double labelWidthMm = 50.8; // 2 inch = 50.8mm
      double labelHeightMm = 25.4; // 1 inch = 25.4mm

      // The printer roll width (58mm for Billplus)
      double rollWidthMm = 58.0;

      if (size.contains('58mm')) {
        rollWidthMm = 58.0;
        labelWidthMm = 50.8;
        labelHeightMm = 25.4;
      } else if (size.contains('50mm x 25mm')) {
        rollWidthMm = 58.0;
        labelWidthMm = 50.0;
        labelHeightMm = 25.0;
      } else if (size.contains('50mm x 38mm') || size.contains('1.5"')) {
        rollWidthMm = 58.0;
        labelWidthMm = 50.0;
        labelHeightMm = 38.0;
      } else if (size.contains('80mm')) {
        rollWidthMm = 80.0;
        labelWidthMm = 72.0;
        labelHeightMm = 40.0;
      } else if (size.contains('75mm x 50mm') || size.contains('3" x 2"')) {
        rollWidthMm = 80.0;
        labelWidthMm = 75.0;
        labelHeightMm = 50.0;
      } else if (size.contains('100mm x 60mm') || size.contains('4" x 2.5"')) {
        rollWidthMm = 110.0;
        labelWidthMm = 100.0;
        labelHeightMm = 60.0;
      } else if (size.contains('Custom') && customWidthMm != null && customHeightMm != null) {
        labelWidthMm = customWidthMm > 0 ? customWidthMm : 50.8;
        labelHeightMm = customHeightMm > 0 ? customHeightMm : 25.4;
        rollWidthMm = labelWidthMm + 8; // 4mm padding each side
      }

      if (size.contains('A4')) {
        // ── A4 24-LABEL SHEET ──
        final labelCount = copies > 0 ? (copies > 24 ? copies : 24) : 24;
        doc.addPage(
          pw.Page(
            pageFormat: PdfPageFormat.a4,
            margin: const pw.EdgeInsets.all(8 * PdfPageFormat.mm),
            build: (pw.Context ctx) {
              return pw.GridView(
                crossAxisCount: 3,
                childAspectRatio: 2.3,
                crossAxisSpacing: 4 * PdfPageFormat.mm,
                mainAxisSpacing: 4 * PdfPageFormat.mm,
                children: List.generate(
                  labelCount,
                  (index) => pw.Container(
                    padding: const pw.EdgeInsets.all(4),
                    decoration: pw.BoxDecoration(
                      border: pw.Border.all(color: PdfColors.grey300, width: 0.5),
                      borderRadius: const pw.BorderRadius.all(pw.Radius.circular(3)),
                    ),
                    child: pw.Column(
                      mainAxisAlignment: pw.MainAxisAlignment.center,
                      crossAxisAlignment: pw.CrossAxisAlignment.center,
                      children: [
                        pw.Text(storeName, style: pw.TextStyle(fontSize: 5.5, fontWeight: pw.FontWeight.bold)),
                        pw.SizedBox(height: 1),
                        pw.Text(productName, maxLines: 1, style: const pw.TextStyle(fontSize: 5)),
                        pw.SizedBox(height: 2),
                        pw.BarcodeWidget(
                          barcode: pw.Barcode.code128(),
                          data: barcode,
                          width: 42 * PdfPageFormat.mm,
                          height: 10 * PdfPageFormat.mm,
                        ),
                      ],
                    ),
                  ),
                ),
              );
            },
          ),
        );
      } else {
        // ── THERMAL STICKER LABEL ──
        // Page size = roll width (58mm) x label height
        // Content is centered within the label area
        final horizontalMargin = (rollWidthMm - labelWidthMm) / 2;
        final pageFormat = PdfPageFormat(
          rollWidthMm * PdfPageFormat.mm,
          labelHeightMm * PdfPageFormat.mm,
          marginLeft: horizontalMargin * PdfPageFormat.mm,
          marginRight: horizontalMargin * PdfPageFormat.mm,
          marginTop: 1.5 * PdfPageFormat.mm,
          marginBottom: 1.5 * PdfPageFormat.mm,
        );

        // Scale font sizes based on label height
        final storeNameFontSize = labelHeightMm <= 25.4 ? 5.5 : (labelHeightMm <= 38 ? 7.0 : 8.0);
        final productNameFontSize = labelHeightMm <= 25.4 ? 5.0 : (labelHeightMm <= 38 ? 6.0 : 7.0);
        final barcodeWidth = labelWidthMm * 0.88 * PdfPageFormat.mm;
        final barcodeHeight = (labelHeightMm * 0.38).clamp(7.0, 18.0) * PdfPageFormat.mm;

        final totalCopies = copies > 0 ? copies : 2;
        for (int i = 0; i < totalCopies; i++) {
          doc.addPage(
            pw.Page(
              pageFormat: pageFormat,
              build: (pw.Context ctx) {
                return pw.Center(
                  child: pw.Column(
                    mainAxisAlignment: pw.MainAxisAlignment.center,
                    crossAxisAlignment: pw.CrossAxisAlignment.center,
                    mainAxisSize: pw.MainAxisSize.min,
                    children: [
                      pw.Text(
                        storeName,
                        style: pw.TextStyle(fontSize: storeNameFontSize, fontWeight: pw.FontWeight.bold),
                        textAlign: pw.TextAlign.center,
                      ),
                      pw.SizedBox(height: 1 * PdfPageFormat.mm),
                      pw.Text(
                        productName,
                        maxLines: 1,
                        style: pw.TextStyle(fontSize: productNameFontSize, fontWeight: pw.FontWeight.bold),
                        textAlign: pw.TextAlign.center,
                      ),
                      pw.SizedBox(height: 1.2 * PdfPageFormat.mm),
                      pw.BarcodeWidget(
                        barcode: pw.Barcode.code128(),
                        data: barcode,
                        width: barcodeWidth,
                        height: barcodeHeight,
                      ),
                    ],
                  ),
                );
              },
            ),
          );
        }
      }

      final pdfBytes = await doc.save();
      final printerService = PrinterService();

      // Check if thermal printer is already connected or can auto-connect
      bool isConn = await printerService.isConnected();
      if (!isConn) {
        isConn = await printerService.autoConnect();
      }

      if (isConn) {
        // Direct print to connected thermal printer!
        try {
          final rasterPages = Printing.raster(pdfBytes, pages: [0], dpi: 203);
          final firstPage = await rasterPages.first;
          final pngBytes = await firstPage.toPng();

          final success = await printerService.printBarcodeStickerDirect(
            pngBytes: pngBytes,
            count: copies,
          );
          if (success) {
            _showSnack('$copies Barcode sticker(s) printed to thermal printer!');
            return;
          }
        } catch (e) {
          debugPrint('Thermal sticker direct print error: $e');
        }
      }

      // If not connected, check paired Bluetooth devices
      final devices = await printerService.getDevices();
      if (devices.isNotEmpty && mounted) {
        final chosen = await showModalBottomSheet<dynamic>(
          context: context,
          backgroundColor: Colors.white,
          shape: const RoundedRectangleBorder(borderRadius: BorderRadius.vertical(top: Radius.circular(20))),
          builder: (sheetCtx) => SafeArea(
            child: Padding(
              padding: const EdgeInsets.symmetric(horizontal: 20, vertical: 16),
              child: Column(
                mainAxisSize: MainAxisSize.min,
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Row(
                    children: [
                      Container(
                        padding: const EdgeInsets.all(8),
                        decoration: BoxDecoration(
                          color: AppColors.primary.withValues(alpha: 0.1),
                          borderRadius: BorderRadius.circular(10),
                        ),
                        child: const Icon(Icons.print_rounded, color: AppColors.primary, size: 22),
                      ),
                      const SizedBox(width: 12),
                      const Expanded(
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.start,
                          children: [
                            Text('Select Printer for Sticker', style: TextStyle(fontWeight: FontWeight.bold, fontSize: 16)),
                            Text('Tap your thermal printer to print sticker', style: TextStyle(fontSize: 12, color: AppColors.textSecondary)),
                          ],
                        ),
                      ),
                    ],
                  ),
                  const SizedBox(height: 14),
                  Flexible(
                    child: ListView.separated(
                      shrinkWrap: true,
                      itemCount: devices.length,
                      separatorBuilder: (_, __) => const SizedBox(height: 6),
                      itemBuilder: (context, index) {
                        final dev = devices[index];
                        return ListTile(
                          leading: const CircleAvatar(
                            backgroundColor: Color(0xFFDCFCE7),
                            child: Icon(Icons.bluetooth_connected_rounded, color: Color(0xFF15803D), size: 20),
                          ),
                          title: Text(dev.name ?? 'Thermal Printer', style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 14)),
                          subtitle: Text(dev.address ?? '', style: const TextStyle(fontSize: 11)),
                          trailing: const Icon(Icons.chevron_right_rounded),
                          tileColor: Colors.grey.shade50,
                          shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                          onTap: () => Navigator.pop(sheetCtx, dev),
                        );
                      },
                    ),
                  ),
                  const SizedBox(height: 10),
                  ListTile(
                    leading: const CircleAvatar(
                      backgroundColor: Color(0xFFE0E7FF),
                      child: Icon(Icons.picture_as_pdf_rounded, color: Color(0xFF4338CA), size: 20),
                    ),
                    title: const Text('System Print / PDF', style: TextStyle(fontWeight: FontWeight.w600, fontSize: 13)),
                    subtitle: const Text('Standard Android print or Wi-Fi printer', style: TextStyle(fontSize: 11)),
                    trailing: const Icon(Icons.chevron_right_rounded),
                    tileColor: Colors.grey.shade50,
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                    onTap: () => Navigator.pop(sheetCtx, 'system_print'),
                  ),
                ],
              ),
            ),
          ),
        );

        if (chosen is BluetoothDevice) {
          final connected = await printerService.connect(chosen);
          if (connected) {
            final rasterPages = Printing.raster(pdfBytes, pages: [0], dpi: 203);
            final firstPage = await rasterPages.first;
            final pngBytes = await firstPage.toPng();

            final success = await printerService.printBarcodeStickerDirect(
              pngBytes: pngBytes,
              count: copies,
            );
            if (success) {
              _showSnack('$copies Barcode sticker(s) printed to ${chosen.name}!');
              return;
            }
          }
        } else if (chosen != 'system_print') {
          return; // User cancelled
        }
      }

      // Fallback: System Print Spooler
      await Printing.layoutPdf(
        onLayout: (PdfPageFormat format) async => pdfBytes,
        name: 'Label_${barcode}_$storeName',
      );
    } catch (e) {
      _showSnack('Thermal printer error: $e', isError: true);
    }
  }

