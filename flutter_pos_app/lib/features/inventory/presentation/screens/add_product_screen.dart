  Future<void> _saveProduct() async {
    final name = _nameController.text.trim();
    if (name.isEmpty) {
      _showSnack('Please enter a product name.', isError: true);
      return;
    }

    final quantityText = _quantityController.text.trim();
    if (quantityText.isEmpty) {
      _showSnack('Please enter product quantity.', isError: true);
      return;
    }
    final stockVal = int.tryParse(quantityText);
    if (stockVal == null) {
      _showSnack('Please enter a valid quantity number.', isError: true);
      return;
    }

    setState(() => _isSaving = true);

    final sku = _skuController.text.trim().isEmpty
        ? 'AUTO-${DateTime.now().millisecondsSinceEpoch}'
        : _skuController.text.trim();
    final String categoryLabel;
    if (widget.category != null && (_selectedCategory == null || _selectedCategoryId == widget.category!.id || _selectedCategory!.name.trim().toLowerCase() == widget.category!.name.trim().toLowerCase())) {
      categoryLabel = widget.category!.name.trim();
    } else if (_selectedCategory != null && _selectedCategory!.name.trim().isNotEmpty) {
      categoryLabel = _selectedCategory!.name.trim();
    } else if (widget.category != null && widget.category!.name.trim().isNotEmpty) {
      categoryLabel = widget.category!.name.trim();
    } else if (widget.editProduct != null && widget.editProduct!.category.trim().isNotEmpty) {
      categoryLabel = widget.editProduct!.category.trim();
    } else {
      categoryLabel = 'General';
    }
    final costVal = double.tryParse(_costController.text.trim()) ?? 0.0;
    final priceVal = double.tryParse(_priceController.text.trim()) ?? costVal;

    String? imageBase64;
    if (_productImage != null) {
      try {
        final pathLower = _productImage!.path.toLowerCase();
        var mime = 'image/jpeg';
        if (pathLower.endsWith('.png')) {
          mime = 'image/png';
        } else if (pathLower.endsWith('.webp')) {
          mime = 'image/webp';
        }
        final bytes = await _productImage!.readAsBytes();
        imageBase64 = 'data:$mime;base64,${base64Encode(bytes)}';
      } catch (e) {
        if (mounted) {
          _showSnack('Could not read product image: $e', isError: true);
          setState(() => _isSaving = false);
        }
        return;
      }
    }

    try {
      final desc = _descriptionController.text.trim();
      final dims = _dimensionsController.text.trim();

      final enabledMarketplaces = <String>[];
      if (_publishToFlipkart) enabledMarketplaces.add('flipkart');
      if (_publishToMeesho) enabledMarketplaces.add('meesho');
      if (_publishToZomato) enabledMarketplaces.add('zomato');
      if (_publishToSwiggy) enabledMarketplaces.add('swiggy');
      if (_publishToEatClub) enabledMarketplaces.add('eatclub');
      if (_publishToShopify) enabledMarketplaces.add('shopify');
      if (_publishToWooCommerce) enabledMarketplaces.add('woocommerce');

      // GST Rate: check input box first, then preset chip, otherwise 0 (optional)
      double gstRateVal = 0.0;
      final gstText = _gstRateController.text.trim();
      if (gstText.isNotEmpty) {
        gstRateVal = double.tryParse(gstText) ?? 0.0;
      } else if (_selectedGstRate > 0) {
        gstRateVal = _selectedGstRate.toDouble();
      }

      final api.Product productResult;
      if (isEditMode) {
        productResult = await ref.read(productRepositoryProvider).updateProduct(
              id: widget.editProduct!.id,
              name: name,
              sku: sku,
              price: priceVal,
              cost: costVal,
              stock: stockVal,
              barcode: _barcodeController.text.trim(),
              category: categoryLabel,
              imageBase64: imageBase64,
              description: desc.isEmpty ? null : desc,
              dimensions: dims.isEmpty ? null : dims,
              marketplaces: enabledMarketplaces,
              taxRate: gstRateVal,
            );
      } else {
        productResult = await ref.read(productRepositoryProvider).createProduct(
              name: name,
              sku: sku,
              price: priceVal,
              cost: costVal,
              stock: stockVal,
              barcode: _barcodeController.text.trim(),
              category: categoryLabel,
              imageBase64: imageBase64,
              description: desc.isEmpty ? null : desc,
              dimensions: dims.isEmpty ? null : dims,
              marketplaces: enabledMarketplaces,
              taxRate: gstRateVal,
            );
      }

      final legacy = Product(
        id: productResult.id,
        name: productResult.name,
        sku: productResult.sku,
        imageUrl: productResult.imageUrl ?? (_productImage == null ? (_existingImageUrl ?? '') : ''),
        quantity: productResult.stock,
        price: productResult.price,
        description: _descriptionController.text.trim(),
        dimensions: productResult.dimensions ?? (dims.isEmpty ? null : dims),
        categoryId: _selectedCategory?.id ?? widget.category?.id ?? '',
        categoryName: categoryLabel.isNotEmpty ? categoryLabel : productResult.category,
        marketplaces: enabledMarketplaces,
        taxRate: gstRateVal,
      );

      try {
        await ProductLocalService().insertProduct(productResult);
      } catch (err) {
        debugPrint('Failed to cache created product in local DB: $err');
      }

      if (!mounted) return;
      ref.invalidate(productsProvider);
      if (categoryLabel.isNotEmpty) {
        ref.invalidate(categoryProductsProvider(categoryLabel));
        final selectedCatId = _selectedCategory?.id ?? widget.category?.id;
        if (!isEditMode && selectedCatId != null && selectedCatId.isNotEmpty) {
          ref.read(categoryRepositoryProvider).localService.incrementProductCount(selectedCatId);
          ref.invalidate(categoriesProvider);
        }
      }
      if (widget.category != null) {
        ref.invalidate(categoryProductsProvider(widget.category!.name.trim()));
      }
      if (widget.editProduct?.category != null && widget.editProduct!.category.isNotEmpty) {
        ref.invalidate(categoryProductsProvider(widget.editProduct!.category.trim()));
      }

      // Universal 1-Click Sync to Flipkart, Meesho, etc. (Run in background so save is instant ~1 sec)
      final token = ref.read(authProvider).token;
      if (enabledMarketplaces.isNotEmpty && token != null) {
        Future.microtask(() async {
          if (_publishToFlipkart) {
            try {
              await MarketplaceRepository().pushProductToFlipkart(
                productId: productResult.id,
                token: token,
              );
            } catch (_) {}
          }
          if (_publishToMeesho) {
            try {
              await MarketplaceRepository().pushProductToMeesho(
                productId: productResult.id,
                token: token,
              );
            } catch (_) {}
          }
          try {
            await MarketplaceRepository().syncProductToPlatforms(
              productId: productResult.id,
              platforms: enabledMarketplaces,
              token: token,
            );
          } catch (e) {
            debugPrint('Universal marketplace background sync: $e');
          }
        });
      }

      if (mounted) {
        _showSnack(isEditMode ? 'Product updated successfully!' : 'Product added successfully!');
        context.pop(legacy);
      }
    } catch (e) {
      if (!mounted) return;
      String err = e.toString();
      if (err.contains('ApiException:')) err = err.split('ApiException:').last.trim();
      _showSnack('Failed to save product: $err', isError: true);
    } finally {
      if (mounted) setState(() => _isSaving = false);
    }
  }

  int get _activeMarketplacesCount {
    int count = 0;
    if (_publishToFlipkart) count++;
    if (_publishToMeesho) count++;
    if (_publishToZomato) count++;
    if (_publishToSwiggy) count++;
    if (_publishToEatClub) count++;
    if (_publishToShopify) count++;
    if (_publishToWooCommerce) count++;
    return count;
  }

